"""**RETRIVAL**"""

def ask_rag(question,n_results=3,verbose=True):
  chunks,sources=retrieve(question,n_results)

  if verbose:
    print(f"\n{'='*60}")
    print(f"Question: {question}")
    print(f"\n{'='*60}")
    print(f"Retrived {len(chunks)} chunks:")
    for i,(chunk,source) in enumerate(zip(chunks,sources)):
      print(f"  [{source['source']}]  {chunk[:80]}....")
    print(f"{'_'*60}")

  context='\n\n'.join(chunks)

  messages=[{

            "role":"system",
            "content" :(
                "you are a helpful assistance that answers question based only on the provided context"
                "If the content does not contain information to answer the question,"
                "say i dont have enough information or information to answer this question"
                "do not make up information or assume anything. strictly answer only form the provided context"
                 )
            },
            {
                "role":"user",
                "content":f"question:{question} context:{context}"
            }

  ]

  response = client.chat.completions.create(
     model='llama-3.3-70b-versatile',
     messages=messages,
     temperature=0.2 #Low temprature for actual answers not for creativity
  )
  answer=response.choices[0].message.content

  if verbose:
    print(f'Answer:{answer}')
    print(f"{'='*60}")
  return answer

