"""**Chunking Strategy**"""

def chunk_document(text,source_name):
  #split on double new lines
  paragraph=text.strip().split('\n\n')

  chunks=[]

  for para in paragraph:
    para=para.strip()
    if len(para)<50:
      continue
    if para.startswith('==='):
      continue
    chunks.append({'text':para,'source':source_name})

  return chunks

